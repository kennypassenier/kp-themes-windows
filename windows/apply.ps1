<#
.SYNOPSIS
    Puts one kp-themes theme on this Windows desktop.

.DESCRIPTION
    Hand-written; the files it copies are generated by gates/generate-desktop.mjs:
    this platform's in themes\<theme>\ beside this script, the ones Linux shares
    (FireDragon, Starship, fish, wallpapers) in ..\shared\<theme>\.
    Every file it changes is copied to <file>.kp-backup-<timestamp> first.
    Current user only: no step needs administrator rights.

    Steps (each can be skipped):
      mica        Mica For Everyone's settings.json
      terminal    Windows Terminal: scheme, window theme, font, acrylic; Arch as default profile if installed
      firedragon  userChrome.css, userContent.css and user.js in every FireDragon profile
      accent      accent colour, dark/light mode, transparency (accent.reg)
      wallpaper   wallpaper.png, if rendered (npm run build:desktop)
      wsl         starship.toml and fish colours inside the Arch WSL distro, if installed

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\desktop\windows\apply.ps1 -Theme synthwave
.EXAMPLE
    .\desktop\windows\apply.ps1 -Theme cyberpunk -Skip wallpaper,accent -DryRun
#>
[CmdletBinding()]
param(
    # Leave it out to pick from a list; -List just prints the list.
    [Parameter(Position = 0)]
    [string]$Theme = '',
    [switch]$List,
    [ValidateSet('fonts', 'mica', 'terminal', 'prompt', 'firedragon', 'accent', 'wallpaper', 'lockscreen', 'windhawk', 'wsl')]
    [string[]]$Skip = @(),
    # Run only these steps; everything else is skipped. Used by the elevated
    # re-run of the lockscreen step.
    [ValidateSet('fonts', 'mica', 'terminal', 'prompt', 'firedragon', 'accent', 'wallpaper', 'lockscreen', 'windhawk', 'wsl')]
    [string[]]$Only = @(),
    # theme: this theme's own Windhawk styles, colours and shape, written into
    # the registry. accent: one set that only follows the accent colour.
    [ValidateSet('accent', 'theme')]
    [string]$WindhawkFlavour = 'theme',
    [string]$WslDistro = 'archlinux',
    [string]$TerminalFont = '',
    # Explorer, the start menu and the notification centre are restarted at the
    # end so the Windhawk styles and the accent colour show at once; -NoRestart
    # leaves them. -RestartExplorer is kept for older shortcuts and does nothing.
    [switch]$NoRestart,
    [switch]$RestartExplorer,
    # Everything under HKLM (Windhawk, the lock screen) needs administrator
    # rights, so the script asks for them once at the start; -NoElevate skips
    # those steps instead.
    [switch]$NoElevate,
    # Wait for a key at the end, for a window opened by double-clicking.
    [switch]$Pause,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2

# The same layout in the repo (desktop\) and in the installed kit
# (~\.config\kp-themes\): windows\ beside shared\.
$Root = $PSScriptRoot
$Shared = Join-Path (Split-Path $Root -Parent) 'shared'
$Stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)

# Windows PowerShell 5 hands a JSON array down the pipeline as one object, so
# enumerate it by hand; PowerShell 7 would unroll it either way.
$All = @()
foreach ($t in (Get-Content (Join-Path $Shared 'themes.json') -Raw | ConvertFrom-Json)) { $All += $t }

function Show-Themes {
    Write-Host ''
    Write-Host '  kp-themes' -ForegroundColor Cyan
    for ($i = 0; $i -lt $All.Count; $i++) {
        $t = $All[$i]
        $kind = if ($t.dark) { 'dark ' } else { 'light' }
        Write-Host ('  {0,2}. {1,-14} {2}  {3}' -f ($i + 1), $t.name, $kind, $t.label)
    }
    Write-Host ''
}

if ($List) { Show-Themes; return }

# No theme named: pick one from the list, so one command is the whole switch.
if (-not $Theme) {
    Show-Themes
    $answer = Read-Host '  Theme (number or name)'
    $Theme = if ($answer -match '^\d+$' -and [int]$answer -ge 1 -and [int]$answer -le $All.Count) { $All[[int]$answer - 1].name } else { $answer.Trim() }
}

$ThemeDir = Join-Path $Root "themes\$Theme"
$SharedDir = Join-Path $Shared $Theme
if (-not (Test-Path (Join-Path $ThemeDir 'terminal.json'))) {
    throw "Unknown theme '$Theme'. Known: $(($All | ForEach-Object { $_.name }) -join ', '). Run 'npm run generate:desktop' if the folder is missing."
}
$Meta = $All | Where-Object { $_.name -eq $Theme }

function Test-Admin {
    try {
        $id = [Security.Principal.WindowsIdentity]::GetCurrent()
        return (New-Object Security.Principal.WindowsPrincipal($id)).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    } catch { return $false }
}

# One UAC prompt for the whole switch: re-run this script elevated with the
# same arguments. An administrator's elevated process is the same user, so
# HKCU, %APPDATA% and ~ are still that user's.
if (-not $DryRun -and -not $NoElevate -and -not (Test-Admin)) {
    # -Command rather than -File, because -File cannot pass a list (-Skip a,b).
    $q = { param($t) "'" + ("$t" -replace "'", "''") + "'" }
    $call = "& $(& $q $PSCommandPath) -Theme $(& $q $Theme)"
    foreach ($k in $PSBoundParameters.Keys) {
        if ($k -eq 'Theme') { continue }
        $v = $PSBoundParameters[$k]
        if ($v -is [switch]) { if ($v.IsPresent) { $call += " -$k" } }
        elseif ($v -is [array]) { $call += " -$k " + (($v | ForEach-Object { & $q $_ }) -join ',') }
        else { $call += " -$k $(& $q $v)" }
    }
    $argv = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', $call)
    try {
        $p = Start-Process -FilePath 'powershell.exe' -Verb RunAs -PassThru -Wait -ArgumentList $argv
        exit $p.ExitCode
    } catch {
        Write-Host '  No administrator rights: Windhawk and the lock screen are skipped.' -ForegroundColor Yellow
        $NoElevate = $true
    }
}
if ($NoElevate -and -not (Test-Admin)) { $Skip = @($Skip) + @('windhawk', 'lockscreen') }

function Say([string]$step, [string]$text, [string]$colour = 'Gray') {
    Write-Host ('  {0,-11}' -f $step) -ForegroundColor Magenta -NoNewline
    Write-Host $text -ForegroundColor $colour
}

function Backup([string]$path) {
    if (Test-Path $path) {
        $target = "$path.kp-backup-$Stamp"
        if (-not $DryRun) { Copy-Item $path $target -Force }
        return $target
    }
    return $null
}

function Write-Text([string]$path, [string]$text) {
    if ($DryRun) { return }
    $dir = Split-Path $path -Parent
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($path, $text, $Utf8NoBom)
}

function Copy-Themed([string]$source, [string]$dest) {
    # Only the file that was there before kp-themes is worth keeping; a previous
    # theme's generated copy can be made again, so it gets no backup.
    $generated = (Test-Path $dest) -and ((Get-Content $dest -TotalCount 1) -match 'GENERATED by kp-themes')
    if (-not $generated) { Backup $dest | Out-Null }
    if (-not $DryRun) {
        $dir = Split-Path $dest -Parent
        if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
        Copy-Item $source $dest -Force
    }
}

# PowerShell 5 turns anything a native program writes to stderr into an error,
# and with ErrorActionPreference = Stop that ends the script, even when the
# program succeeded (reg.exe reports "completed successfully" on stderr).
# Run native programs through this and judge them by their exit code.
function Invoke-Native([string]$exe, [string[]]$arguments) {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try { $output = & $exe @arguments 2>&1 | ForEach-Object { "$_" } }
    finally { $ErrorActionPreference = $old }
    return [pscustomobject]@{ Code = $LASTEXITCODE; Output = @($output) }
}

# Strict mode refuses .PSObject.Properties.Name on an object with no properties.
function Has($object, [string]$name) { return ($null -ne $object) -and ($null -ne $object.PSObject.Properties[$name]) }

function Set-Prop($object, [string]$name, $value) {
    if (Has $object $name) { $object.$name = $value }
    else { $object | Add-Member -NotePropertyName $name -NotePropertyValue $value }
}

# Windows Terminal writes JSON with comments and trailing commas; PowerShell 5 reads neither.
function Read-Jsonc([string]$path) {
    $text = Get-Content $path -Raw -Encoding UTF8
    $text = [regex]::Replace($text, '(?m)^\s*//.*$', '')
    $text = [regex]::Replace($text, ',(\s*[}\]])', '$1')
    return $text | ConvertFrom-Json
}

function Test-Font([string]$face) {
    foreach ($hive in 'HKLM:', 'HKCU:') {
        $key = "$hive\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Fonts"
        if (Test-Path $key) {
            $names = (Get-Item $key).GetValueNames()
            if ($names | Where-Object { $_ -like "$face*" }) { return $true }
        }
    }
    return $false
}

# One gate for every step: -Only wins, -Skip removes.
function Step([string]$name) {
    if ($Only.Count -gt 0) { return $Only -contains $name }
    return $Skip -notcontains $name
}

# SendMessageTimeout to every window: how Windows tells programs that the
# colours, the fonts or the wallpaper changed.
Add-Type -Namespace KpShell -Name Native -MemberDefinition @'
[DllImport("user32.dll", CharSet = CharSet.Unicode)]
public static extern System.IntPtr SendMessageTimeoutW(System.IntPtr hWnd, uint msg, System.IntPtr w, string l, uint flags, uint timeout, out System.IntPtr result);
'@ -ErrorAction SilentlyContinue
function Send-SettingChange([string]$area) {
    $out = [IntPtr]::Zero
    [KpShell.Native]::SendMessageTimeoutW([IntPtr]0xffff, 0x001A, [IntPtr]::Zero, $area, 2, 2000, [ref]$out) | Out-Null
}

Write-Host ''
Write-Host "  kp-themes -> Windows: KP $($Meta.label) ($Theme)" -ForegroundColor Cyan
if ($DryRun) { Write-Host '  dry run: nothing is written' -ForegroundColor Yellow }
Write-Host ''

# --- Fonts ---------------------------------------------------------------------
if (Step 'fonts') {
    $fonts = Join-Path $Shared 'fonts'
    if ((Get-ChildItem $fonts -Filter '*.ttf' -ErrorAction SilentlyContinue | Measure-Object).Count -gt 0) {
        # A font problem must not stop the switch: say so and go on.
        if (-not $DryRun) {
            try { & (Join-Path $Root 'install-fonts.ps1') -Source $fonts }
            catch { Say 'fonts' "skipped: $($_.Exception.Message)" 'Yellow' }
        }
        else { Say 'fonts' "would install the fonts in $fonts" }
    } else { Say 'fonts' 'no fonts in shared\fonts (npm run build:desktop), skipped' 'DarkGray' }
}

# --- Mica For Everyone --------------------------------------------------------
if (Step 'mica') {
    $pkg = Get-ChildItem (Join-Path $env:LOCALAPPDATA 'Packages') -Directory -Filter 'MicaForEveryone*' -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($pkg) {
        Copy-Themed (Join-Path $ThemeDir 'mica-settings.json') (Join-Path $pkg.FullName 'LocalState\settings.json')
        # It reads the file at start, so restart it: the folder name is its package family.
        if (-not $DryRun) {
            Get-Process -Name 'MicaForEveryone*' -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
            try {
                Start-Process 'explorer.exe' "shell:AppsFolder\$($pkg.Name)!App"
                Say 'mica' 'settings.json replaced and Mica For Everyone restarted'
            } catch { Say 'mica' 'settings.json replaced; start Mica For Everyone yourself to pick it up' 'Yellow' }
        } else { Say 'mica' 'would replace settings.json' }
    } else { Say 'mica' 'Mica For Everyone not found, skipped' 'DarkGray' }
}

# --- Windows Terminal ---------------------------------------------------------
if (Step 'terminal') {
    $candidates = @(
        (Join-Path $env:LOCALAPPDATA 'Packages\Microsoft.WindowsTerminal_8wekyb3d8bbwe\LocalState\settings.json'),
        (Join-Path $env:LOCALAPPDATA 'Packages\Microsoft.WindowsTerminalPreview_8wekyb3d8bbwe\LocalState\settings.json'),
        (Join-Path $env:LOCALAPPDATA 'Microsoft\Windows Terminal\settings.json')
    ) | Where-Object { Test-Path $_ }

    $generated = Get-Content (Join-Path $ThemeDir 'terminal.json') -Raw | ConvertFrom-Json
    $face = $TerminalFont
    if (-not $face) {
        # The registry lists a font by its file name ("JetBrainsMono NFM Regular"), but
        # Windows Terminal looks it up by its family name ("JetBrainsMono Nerd Font Mono").
        # Each pair is: what to look for in the registry, what to write in settings.json.
        $fonts = @(
            @('JetBrainsMono Nerd Font Mono', 'JetBrainsMono Nerd Font Mono'),
            @('JetBrainsMono NFM', 'JetBrainsMono Nerd Font Mono'),
            @('JetBrainsMono Nerd Font', 'JetBrainsMono Nerd Font'),
            @('JetBrainsMono NF', 'JetBrainsMono Nerd Font'),
            @('JetBrains Mono', 'JetBrains Mono'),
            @('CaskaydiaCove', 'CaskaydiaCove Nerd Font Mono'),
            @('Cascadia Code', 'Cascadia Code')
        )
        foreach ($f in $fonts) {
            if (Test-Font $f[0]) { $face = $f[1]; break }
        }
    }

    if (-not $candidates) { Say 'terminal' 'Windows Terminal settings.json not found (open Terminal once first), skipped' 'DarkGray' }
    foreach ($path in $candidates) {
        $s = Read-Jsonc $path
        $name = $generated.scheme.name

        $schemes = @()
        if (Has $s 'schemes') { $schemes = @($s.schemes | Where-Object { $_.name -ne $name }) }
        Set-Prop $s 'schemes' (@($schemes) + $generated.scheme)

        $themes = @()
        if (Has $s 'themes') { $themes = @($s.themes | Where-Object { $_.name -ne $name }) }
        Set-Prop $s 'themes' (@($themes) + $generated.theme)
        Set-Prop $s 'theme' $name

        if (-not (Has $s 'profiles')) { Set-Prop $s 'profiles' ([pscustomobject]@{ defaults = [pscustomobject]@{}; list = @() }) }
        if ($s.profiles -is [array]) { Set-Prop $s 'profiles' ([pscustomobject]@{ defaults = [pscustomobject]@{}; list = $s.profiles }) }
        if (-not (Has $s.profiles 'defaults') -or $null -eq $s.profiles.defaults) { Set-Prop $s.profiles 'defaults' ([pscustomobject]@{}) }
        $d = $s.profiles.defaults
        Set-Prop $d 'colorScheme' $name
        # A profile with its own KP scheme would keep the old theme: let it
        # inherit from the defaults instead.
        foreach ($profile in @($s.profiles.list)) {
            if ((Has $profile 'colorScheme') -and ("$($profile.colorScheme)" -like 'KP *')) { $profile.PSObject.Properties.Remove('colorScheme') }
        }
        Set-Prop $d 'opacity' 88
        Set-Prop $d 'useAcrylic' $true
        Set-Prop $d 'padding' '10, 8'
        Set-Prop $d 'cursorShape' 'bar'
        if ($face) { Set-Prop $d 'font' ([pscustomobject]@{ face = $face; size = 11 }) }

        # Arch in WSL as the default tab, starting in the Linux home.
        $arch = @($s.profiles.list) | Where-Object {
            (Has $_ 'source') -and ($_.source -like '*Wsl*') -and ($_.name -match $WslDistro)
        } | Select-Object -First 1
        if ($arch) {
            Set-Prop $s 'defaultProfile' $arch.guid
            Set-Prop $arch 'startingDirectory' '~'
            Set-Prop $arch 'hidden' $false
        }

        Backup $path | Out-Null
        Write-Text $path (($s | ConvertTo-Json -Depth 64) + "`n")
        $note = if ($face) { "font $face" } else { 'no Nerd Font found: winget install DEVCOM.JetBrainsMonoNerdFont' }
        $archNote = if ($arch) { "; default profile: $($arch.name)" } else { '' }
        Say 'terminal' "scheme and window theme '$name', $note$archNote"
    }
}

# --- The PowerShell prompt (Oh My Posh) ------------------------------------------
# The theme's config goes to one fixed path, and both PowerShell profiles (7 and
# Windows PowerShell 5) start Oh My Posh with that path. $PROFILE loads after
# every other profile, so this prompt wins over one started elsewhere.
if (Step 'prompt') {
    $omp = Join-Path $ThemeDir 'prompt.omp.json'
    if (-not (Get-Command oh-my-posh -ErrorAction SilentlyContinue)) {
        Say 'prompt' 'Oh My Posh is not installed, skipped' 'DarkGray'
    } elseif (-not (Test-Path $omp)) {
        Say 'prompt' 'no prompt.omp.json for this theme, skipped' 'DarkGray'
    } elseif ($DryRun) {
        Say 'prompt' 'would write the prompt config and the profile line'
    } else {
        $state = Join-Path $HOME '.config\kp-themes'
        New-Item -ItemType Directory -Path $state -Force | Out-Null
        Copy-Item $omp (Join-Path $state 'prompt.omp.json') -Force
        # Documents may be redirected (OneDrive); ask Windows where it is.
        $docs = [Environment]::GetFolderPath('MyDocuments')
        if (-not $docs) { $docs = Join-Path $HOME 'Documents' }
        $block = @(
            '# kp-themes: prompt (begin) - the prompt of the active kp-theme; delete this block to undo',
            'if (Get-Command oh-my-posh -ErrorAction SilentlyContinue) {',
            '    oh-my-posh init pwsh --config "$HOME\.config\kp-themes\prompt.omp.json" | Invoke-Expression',
            '}',
            '# kp-themes: prompt (end)'
        ) -join "`r`n"
        foreach ($folder in 'PowerShell', 'WindowsPowerShell') {
            $profilePath = Join-Path $docs "$folder\Microsoft.PowerShell_profile.ps1"
            [string]$text = if (Test-Path $profilePath) { Get-Content $profilePath -Raw } else { '' }
            if ($text -notmatch 'kp-themes: prompt \(begin\)') {
                Backup $profilePath | Out-Null
                Write-Text $profilePath (($text.TrimEnd() + "`r`n`r`n" + $block + "`r`n").TrimStart())
            }
        }
        Say 'prompt' "Oh My Posh prompt in KP $($Meta.label)'s colours; open a new tab to see it"
    }
}

# --- FireDragon -----------------------------------------------------------------
if (Step 'firedragon') {
    # Windows paths ignore case, so FireDragon and firedragon can be one folder: compare them resolved.
    $bases = @((Join-Path $env:APPDATA 'FireDragon'), (Join-Path $env:APPDATA 'garuda\firedragon')) |
        Where-Object { Test-Path $_ } | ForEach-Object { (Resolve-Path $_).Path } | Sort-Object -Unique
    $profiles = @()
    foreach ($base in $bases) {
        $profiles += Get-ChildItem $base -Recurse -Depth 3 -Filter 'prefs.js' -ErrorAction SilentlyContinue | ForEach-Object { $_.Directory.FullName }
    }
    # Sort-Object -Unique ignores case, Select-Object -Unique does not. The updater's
    # BackgroundTask profiles never show a window, so they are left alone.
    $profiles = @($profiles | Sort-Object -Unique | Where-Object { (Split-Path $_ -Leaf) -notmatch 'BackgroundTask' })
    if (-not $profiles) { Say 'firedragon' 'no FireDragon profile found (start it once first), skipped' 'DarkGray' }
    $userJs = Get-Content (Join-Path $Shared 'firedragon-user.js') -Raw
    foreach ($p in $profiles) {
        Copy-Themed (Join-Path $SharedDir 'firedragon\userChrome.css') (Join-Path $p 'chrome\userChrome.css')
        Copy-Themed (Join-Path $SharedDir 'firedragon\userContent.css') (Join-Path $p 'chrome\userContent.css')
        # The kp block is replaced on every run, so a changed firedragon-user.js arrives too.
        $dest = Join-Path $p 'user.js'
        [string]$existing = if (Test-Path $dest) { Get-Content $dest -Raw } else { '' }
        $block = '(?s)// kp-themes: begin.*?// kp-themes: end\r?\n?'
        if ($existing -notmatch 'kp-themes: begin') { Backup $dest | Out-Null }
        $rest = ([regex]::Replace($existing, $block, '')).TrimEnd()
        Write-Text $dest (((@($rest, $userJs.TrimEnd()) | Where-Object { $_ }) -join "`n`n") + "`n")
        Say 'firedragon' "$(Split-Path $p -Leaf): chrome/ written"
    }
    # userChrome.css is read once, at start-up, so a running FireDragon keeps the old theme.
    $running = @(Get-Process -Name 'firedragon' -ErrorAction SilentlyContinue)
    if ($running -and -not $DryRun) {
        $exe = ($running | Where-Object { $_.Path } | Select-Object -First 1).Path
        $answer = if ($Pause) { Read-Host '  firedragon  FireDragon is running. Restart it now to show the theme? Tabs come back. [Y/n]' } else { 'n' }
        if ($answer -notmatch '^[nN]') {
            # A polite close first, so the session is saved and the tabs return.
            $running | Where-Object { $_.MainWindowHandle -ne 0 } | ForEach-Object { $_.CloseMainWindow() | Out-Null }
            $deadline = (Get-Date).AddSeconds(15)
            while ((Get-Process -Name 'firedragon' -ErrorAction SilentlyContinue) -and (Get-Date) -lt $deadline) { Start-Sleep -Milliseconds 300 }
            if (Get-Process -Name 'firedragon' -ErrorAction SilentlyContinue) {
                Say 'firedragon' 'FireDragon did not close (a dialog open?); close it yourself and start it again' 'Yellow'
            } elseif ($exe) {
                # Through Explorer, so the browser does not inherit this script's admin rights.
                Start-Process explorer.exe -ArgumentList "`"$exe`""
                Say 'firedragon' 'restarted with the new theme'
            }
        } else {
            Say 'firedragon' 'FireDragon is running: close every window and start it again to see the theme' 'Yellow'
        }
    }
}

# --- Accent colour and dark mode ----------------------------------------------
if (Step 'accent') {
    if (-not $DryRun) {
        $r = Invoke-Native 'reg.exe' @('import', (Join-Path $ThemeDir 'accent.reg'))
        if ($r.Code -ne 0) { throw "reg.exe import failed ($($r.Code)): $($r.Output -join ' ')" }
    }
    if (-not $DryRun) { Send-SettingChange 'ImmersiveColorSet' }
    Say 'accent' "accent colour and $(if ($Meta.dark) { 'dark' } else { 'light' }) mode set"
}

# --- Wallpaper ----------------------------------------------------------------------
if (Step 'wallpaper') {
    $png = Join-Path $SharedDir 'wallpaper.png'
    if (Test-Path $png) {
        $keep = Join-Path ([Environment]::GetFolderPath('MyPictures')) "kp-themes\$Theme.png"
        if (-not $DryRun) {
            New-Item -ItemType Directory -Path (Split-Path $keep -Parent) -Force | Out-Null
            Copy-Item $png $keep -Force
            Add-Type -TypeDefinition @'
using System.Runtime.InteropServices;
public static class KpWallpaper {
    [DllImport("user32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    public static extern bool SystemParametersInfo(int action, int param, string value, int flags);
}
'@ -ErrorAction SilentlyContinue
            # SPI_SETDESKWALLPAPER, SPIF_UPDATEINIFILE | SPIF_SENDCHANGE
            [KpWallpaper]::SystemParametersInfo(20, 0, $keep, 3) | Out-Null
        }
        Say 'wallpaper' "set from $keep"
    } else { Say 'wallpaper' 'no wallpaper.png (run: npm run build:desktop), skipped' 'DarkGray' }
}

# --- Lock screen and sign-in screen -------------------------------------------------
# PersonalizationCSP is the one place every edition of Windows 11 reads, and the
# sign-in screen shows the lock screen picture, so both are set here. It writes
# under HKLM, so this step needs administrator rights and asks for them once.
if (Step 'lockscreen') {
    $publicPictures = 'C:\Users\Public\Pictures\kp-themes'
    $desktop = Join-Path $SharedDir 'wallpaper.png'
    $lock = Join-Path $SharedDir 'wallpaper-lock.png'
    if (-not (Test-Path $desktop) -or -not (Test-Path $lock)) {
        Say 'lockscreen' 'no rendered wallpapers (run: npm run build:desktop), skipped' 'DarkGray'
    } elseif ($DryRun) {
        Say 'lockscreen' "would copy both pictures to $publicPictures and import personalization.reg"
    } elseif (Test-Admin) {
        New-Item -ItemType Directory -Path $publicPictures -Force | Out-Null
        Copy-Item $desktop (Join-Path $publicPictures "$Theme.png") -Force
        Copy-Item $lock (Join-Path $publicPictures "$Theme-lock.png") -Force
        $r = Invoke-Native 'reg.exe' @('import', (Join-Path $ThemeDir 'personalization.reg'))
        if ($r.Code -ne 0) { throw "reg.exe import failed ($($r.Code)): $($r.Output -join ' ')" }
        Say 'lockscreen' 'lock and sign-in picture set; lock with Win+L to see it'
    } else {
        Say 'lockscreen' 'asking for administrator rights (the lock screen lives under HKLM)...' 'Yellow'
        $p = Start-Process -FilePath 'powershell.exe' -Verb RunAs -PassThru -Wait -ArgumentList @(
            '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$PSCommandPath`"", '-Theme', $Theme, '-Only', 'lockscreen')
        if ($p.ExitCode -eq 0) { Say 'lockscreen' 'lock and sign-in picture set' }
        else { Say 'lockscreen' "the elevated run ended with $($p.ExitCode); run this script as administrator to set it" 'Yellow' }
    }
}

# --- Windhawk: taskbar, start menu, notification centre, Explorer, menus -----------
# Windhawk keeps what its Settings tab saves as flat values under
# HKLM\SOFTWARE\Windhawk\Engine\Mods\<mod>\Settings. windhawk.reg replaces all
# five mods' settings; bumping each mod's SettingsChangeTime is what the Settings
# tab does after a save, and the restart at the end reloads the processes the
# mods live in.
if (Step 'windhawk') {
    $reg = if ($WindhawkFlavour -eq 'accent') { Join-Path $Root 'windhawk-accent\windhawk.reg' } else { Join-Path $ThemeDir 'windhawk.reg' }
    $mods = 'HKLM:\SOFTWARE\Windhawk\Engine\Mods'
    if (-not (Test-Path $mods)) {
        Say 'windhawk' 'Windhawk is not installed (windhawk.net), skipped' 'DarkGray'
    } elseif ($DryRun) {
        Say 'windhawk' "would import $reg"
    } else {
        # The start button picture the taskbar styles point at.
        $startPng = Join-Path $ThemeDir 'start.png'
        if (Test-Path $startPng) {
            $startDir = 'C:\Users\Public\Pictures\kp-themes\start'
            New-Item -ItemType Directory -Path $startDir -Force | Out-Null
            Copy-Item $startPng (Join-Path $startDir "$Theme.png") -Force
        }
        $r = Invoke-Native 'reg.exe' @('import', $reg)
        if ($r.Code -ne 0) { throw "reg.exe import failed ($($r.Code)): $($r.Output -join ' ')" }
        $now = [int][DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
        foreach ($mod in Get-ChildItem $mods) {
            Set-ItemProperty -Path $mod.PSPath -Name 'SettingsChangeTime' -Value $now -Type DWord
        }
        $flavour = if ($WindhawkFlavour -eq 'accent') { 'accent-following styles' } else { "KP $($Meta.label)'s own styles" }
        Say 'windhawk' "$flavour written for 5 mods"
    }
}

# --- The shell inside WSL -------------------------------------------------------------
if (Step 'wsl') {
    $distros = @()
    if (Get-Command wsl.exe -ErrorAction SilentlyContinue) {
        # wsl.exe prints UTF-16; PowerShell reads it with a NUL after every letter.
        $distros = @((Invoke-Native 'wsl.exe' @('--list', '--quiet')).Output | ForEach-Object { ($_ -replace "`0", '').Trim() } | Where-Object { $_ })
    }
    if ($distros -contains $WslDistro) {
        $star = (Join-Path $SharedDir 'starship.toml') -replace '\\', '/'
        $fish = (Join-Path $SharedDir 'kp-colors.fish') -replace '\\', '/'
        # PowerShell 5 mangles quotes in native arguments, so the script travels as base64.
        $sh = "set -e`nmkdir -p ~/.config/fish/conf.d`ncp `"`$(wslpath -u '$star')`" ~/.config/starship.toml`ncp `"`$(wslpath -u '$fish')`" ~/.config/fish/conf.d/kp-colors.fish`n"
        $b64 = [Convert]::ToBase64String($Utf8NoBom.GetBytes($sh))
        if (-not $DryRun) {
            $r = Invoke-Native 'wsl.exe' @('-d', $WslDistro, '-e', 'sh', '-c', "echo $b64 | base64 -d | sh")
            if ($r.Code -ne 0) { throw "copying into $WslDistro failed ($($r.Code)): $($r.Output -join ' ')" }
        }
        Say 'wsl' "starship.toml and fish colours copied into $WslDistro"
    } else { Say 'wsl' "no WSL distro '$WslDistro' (Tools\Setup WSL (Arch).cmd installs it), skipped" 'DarkGray' }
}

# --- Reload the shell -------------------------------------------------------------------
# The taskbar and Explorer live in explorer.exe, the start menu and the
# notification centre in their own hosts; Windows restarts all three at once.
if (-not $DryRun -and -not $NoRestart) {
    foreach ($name in 'StartMenuExperienceHost', 'ShellExperienceHost', 'explorer') {
        Get-Process -Name $name -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    }
    Say 'shell' 'Explorer, start menu and notification centre restarted'
}

if (-not $DryRun) {
    $state = Join-Path $HOME '.config\kp-themes'
    New-Item -ItemType Directory -Path $state -Force | Out-Null
    Set-Content -Path (Join-Path $state 'current.txt') -Value $Theme -Encoding ASCII
}

